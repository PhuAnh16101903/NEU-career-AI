import fs from 'node:fs';
import assert from 'node:assert/strict';
import { JSDOM } from 'jsdom';
const html = fs.readFileSync(new URL('../public/christmas-auth/index.html', import.meta.url), 'utf8');
const script = fs.readFileSync(new URL('../public/christmas-auth/js/neu-register-steps.js', import.meta.url), 'utf8');
const dom = new JSDOM(html, {url:'https://example.test/christmas-auth/index.html',runScripts:'outside-only'});
const { document, Event, MutationObserver } = dom.window;
dom.window.eval(script);
const form = document.getElementById('register-form');
const profile = document.getElementById('neu-profile-dialog');
assert(form.classList.contains('neu-register-wizard'));
assert.equal(document.querySelector('.hotel-brand').getAttribute('aria-label'), 'Đại học Kinh tế Quốc dân (NEU)');
assert(document.querySelector('.holiday-logo-day').getAttribute('src').includes('neu-seal.png'));
const fields = [...form.querySelectorAll(':scope > .field')];
const next = form.querySelector('.neu-register-next');
assert.deepEqual(fields.map(f => f.hidden),[false,true,true,true]);
next.click();
assert.equal(document.getElementById('register-name').getAttribute('aria-invalid'), 'true');
assert.equal(document.getElementById('register-name-error').hidden,false);
const fill = (id,value) => { const el=document.getElementById(id);el.value=value;el.dispatchEvent(new Event('input',{bubbles:true})); };
fill('register-name','Nguyễn Văn A');next.click();
assert.deepEqual(fields.map(f => f.hidden),[true,false,true,true]);
fill('register-email','neu.student@example.edu.vn');next.click();
fill('register-password','LongPassword123!');next.click();
assert.deepEqual(fields.map(f => f.hidden),[true,true,true,false]);
fill('register-confirm','LongPassword123!');
assert.equal(form.querySelector(':scope > .submit').hidden, false);
assert.equal(form.querySelector('.neu-register-progress-caption').textContent, 'Câu hỏi 4/6');
assert.equal(new dom.window.FormData(form).get('email'), 'neu.student@example.edu.vn');
const captured=[];
form.addEventListener('submit',()=>captured.push('original handler reached'));
form.dispatchEvent(new Event('submit',{bubbles:true,cancelable:true}));
assert.deepEqual(captured,['original handler reached']);
assert.equal(profile.querySelector('.neu-register-progress-caption').textContent, 'Câu hỏi 5/6');
const profileNext = profile.querySelector('.neu-register-next');
profileNext.click();
assert.equal(profile.querySelector('.neu-register-progress-caption').textContent, 'Câu hỏi 6/6');
assert.equal(profile.querySelector('#neu-profile-form > .submit').hidden, false);
console.log('PASS: NEU seal, 4 registration questions + 2 profile questions, next/validation, final legacy submit and form payload.');
